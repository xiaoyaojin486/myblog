SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 表结构：tool_category（分类）
-- ------------------------------------------------------------
DROP TABLE IF EXISTS `tool_category`;
CREATE TABLE `tool_category` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `name` varchar(50) COLLATE utf8mb4_general_ci NOT NULL COMMENT '分类名',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序（越小越靠前）',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态:0停用,1启用',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_status_sort` (`status`,`sort`)
) ENGINE=InnoDB AUTO_INCREMENT=13 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='运维工具箱-分类';

-- ------------------------------------------------------------
-- 表结构：tool_command（命令）
-- ------------------------------------------------------------
DROP TABLE IF EXISTS `tool_command`;
CREATE TABLE `tool_command` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `name` varchar(100) COLLATE utf8mb4_general_ci NOT NULL COMMENT '用途标题',
  `command` varchar(500) COLLATE utf8mb4_general_ci NOT NULL COMMENT '命令原文',
  `category_id` bigint NOT NULL COMMENT '分类ID',
  `description` varchar(255) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '说明/示例/注意事项',
  `risk_level` tinyint NOT NULL DEFAULT '0' COMMENT '风险:0只读,1变更,2高危',
  `sort` int NOT NULL DEFAULT '0' COMMENT '排序（越小越靠前）',
  `status` tinyint NOT NULL DEFAULT '1' COMMENT '状态:0下架,1上架',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_status_sort` (`status`,`sort`),
  KEY `idx_category` (`category_id`)
) ENGINE=InnoDB AUTO_INCREMENT=201 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='运维工具箱-命令';

